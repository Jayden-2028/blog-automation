// 키워드 어휘로 "의학 주제인가"를 판정하는 규칙(순수 함수).
//
// 왜 필요한가(SPRINT_2_DESIGN.md 5절): 실측 확인 결과 "아기 셔더링어택 증상" 같은 육아 의학 키워드는
// 웹문서 검색 10건이 전부 네이버 인플루언서 블로그·커뮤니티였다(공공 0, 의료 0). 영아 경련 감별
// 같은 주제를 이런 근거만으로 단정적으로 쓰면 잘못된 의학 정보를 퍼뜨릴 위험이 있다.
//
// 사용자 결정(2026-08-27): 의학 주제라고 원고 생성 자체를 막지 않는다. 대신 이 판정 결과로
// (1) 원고 프롬프트에 안전 규칙을 추가하고 (2) 자동 검수를 통과해도 사람이 직접 출처를 눌러
// 확인해야만 다음 단계로 넘어가게 한다(article_jobs.metadata.requiresMedicalReview).
//
// 설계 원칙: 보수적으로, 그러나 넓게 잡는다 - 이 판정의 오탐 비용(불필요한 사람 확인 1건)이
// 미탐 비용(의학 정보가 검수 없이 나감)보다 훨씬 싸다. keywordCategoryRules.ts와 반대 방향이다 -
// 거기서는 오탐(잘못된 카테고리로 원고가 감)을 피하려 보수적이었지만, 여기서는 미탐을 피하려
// 의도적으로 넓게 잡는다.
//
// 다만 2글자 이하의 짧은 토큰은 넣지 않는다 - 예를 들어 "경기"는 "경기도"·"경기침체" 같은 무관한
// 단어에도 부분 문자열로 걸려 오탐이 폭증한다. 그런 경우 "경련"처럼 더 구체적인 동의어를 쓴다.

const MEDICAL_TERMS: readonly string[] = [
  // 증상/징후
  "증상", "발열", "고열", "경련", "열경련", "연축", "발진", "구토", "설사", "탈수",
  "황달", "통증", "복통", "두통", "치통", "근육통", "요통", "흉통", "부종",
  "삼킴", "질식", "쇼크", "탈장",
  // 질환명
  "아토피", "수족구", "장염", "중이염", "폐렴", "기관지염", "축농증", "결막염",
  "영아연축", "감염", "알레르기",
  // 진료/처치
  "진단", "치료", "처방", "부작용", "복용법", "복용량", "예방접종", "접종",
  "해열제", "진통제", "항생제", "응급실", "응급처치", "화상",
];

/**
 * 키워드가 의학 주제를 다루는지 판정한다. 확실한 신호가 하나라도 있으면 true를 반환한다.
 * keywordCategoryRules.classifyKeywordCategory와 달리 여러 규칙 중 첫 매칭이 아니라, 단일 term
 * 집합에 대한 포함 여부만 본다 - 카테고리를 나누는 게 아니라 "위험 신호가 있는가"만 판정하기 때문이다.
 */
export function isMedicalTopic(keyword: string): boolean {
  const normalized = keyword.trim().toLowerCase();
  if (!normalized) return false;
  return MEDICAL_TERMS.some((term) => normalized.includes(term));
}
